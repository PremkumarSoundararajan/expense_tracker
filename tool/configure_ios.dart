import 'dart:io';

/// OAuth client IDs are public configuration, never client secrets. Restrict
/// syntax before writing an xcconfig so newlines or build-setting expressions
/// cannot be injected through a CI environment variable.
String iosGoogleSignInSettings(String clientId) {
  final value = clientId.trim();
  if (!RegExp(r'^\d+-[A-Za-z0-9_-]+\.apps\.googleusercontent\.com$')
      .hasMatch(value)) {
    throw const FormatException(
      'Supply the client ID of a Google OAuth iOS client, ending in .apps.googleusercontent.com.',
    );
  }
  const webClientId =
      '832232205995-r4b63brhvj3kbo193gckj4jgpg5oo2pi.apps.googleusercontent.com';
  if (value == webClientId) {
    throw const FormatException(
      'This is Pocket Ledger’s web client. Create an iOS OAuth client for com.premkumar.pocketledger instead.',
    );
  }
  final reversed = value.split('.').reversed.join('.');
  return '// Generated by tool/configure_ios.dart. Do not edit by hand.\n'
      'GOOGLE_IOS_CLIENT_ID = $value\n'
      'GOOGLE_IOS_REVERSED_CLIENT_ID = $reversed\n';
}

Future<void> writeIosGoogleSignInSettings(
  String clientId,
  Directory project,
) async {
  final settings = iosGoogleSignInSettings(clientId);
  final file = File('${project.path}/ios/Flutter/GoogleSignIn.xcconfig');
  if (!await file.parent.exists()) {
    throw const FileSystemException(
      'Run this command from the Pocket Ledger project root.',
    );
  }
  await file.writeAsString(settings, flush: true);
}

Future<void> main(List<String> args) async {
  if (args.contains('--help')) {
    stdout.writeln(
      'From the project root: dart run tool/configure_ios.dart --client-id=YOUR_IOS_CLIENT_ID\n'
      'Alternatively set GOOGLE_IOS_CLIENT_ID in the environment.',
    );
    return;
  }
  try {
    String? clientId;
    for (final arg in args) {
      if (!arg.startsWith('--client-id=') || clientId != null) {
        throw const FormatException(
          'Expected one --client-id= value, or use GOOGLE_IOS_CLIENT_ID.',
        );
      }
      clientId = arg.substring('--client-id='.length);
    }
    clientId ??= Platform.environment['GOOGLE_IOS_CLIENT_ID'];
    if (clientId == null || clientId.trim().isEmpty) {
      throw const FormatException(
        'GOOGLE_IOS_CLIENT_ID is missing. Create a Google iOS OAuth client for com.premkumar.pocketledger.',
      );
    }
    await writeIosGoogleSignInSettings(clientId, Directory.current);
    stdout.writeln(
      'Configured iOS Google sign-in and its matching callback scheme.',
    );
  } on Object catch (error) {
    stderr.writeln('iOS configuration failed: $error');
    exitCode = 1;
  }
}
